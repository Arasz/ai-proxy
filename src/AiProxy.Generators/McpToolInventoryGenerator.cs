using System;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace AiProxy.Generators;

/// <summary>Derives the MCP inventory and requires explicit names and all four behavior hints.</summary>
[Generator]
public sealed class McpToolInventoryGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor MissingName = new(
        "APGEN001", "MCP tool name is required", "MCP tool method '{0}' must declare a non-empty Name",
        "McpToolInventory", DiagnosticSeverity.Error, true);

    private static readonly DiagnosticDescriptor MissingHint = new(
        "APGEN002", "Explicit MCP behavior hint is required", "MCP tool method '{0}' must explicitly declare boolean {1}",
        "McpToolInventory", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var tools = context.SyntaxProvider.ForAttributeWithMetadataName(
            "ModelContextProtocol.Server.McpServerToolAttribute",
            static (node, _) => node is MethodDeclarationSyntax,
            static (syntax, _) => new Tool((IMethodSymbol)syntax.TargetSymbol, syntax.Attributes[0]));

        context.RegisterSourceOutput(tools.Collect(), static (output, tools) =>
        {
            var source = new StringBuilder(
                "// <auto-generated/>\nnamespace AiProxy.Mcp;\ninternal static class McpToolInventoryGenerated\n{\n    internal static global::System.Collections.Generic.IReadOnlyList<string> Names { get; } = new string[]\n    {\n");
            foreach (var tool in tools.OrderBy(static tool => tool.Name, StringComparer.Ordinal))
            {
                if (tool.Name is not { Length: > 0 } name || string.IsNullOrWhiteSpace(name))
                {
                    output.ReportDiagnostic(Diagnostic.Create(MissingName, tool.Method.Locations.FirstOrDefault(), tool.Method.Name));
                }
                else
                {
                    source.Append("        ").Append(SymbolDisplay.FormatLiteral(name, true)).AppendLine(",");
                }

                foreach (var hint in new[] { "ReadOnly", "Destructive", "Idempotent", "OpenWorld" })
                {
                    if (!tool.Attribute.NamedArguments.Any(argument => argument.Key == hint && argument.Value.Value is bool))
                    {
                        output.ReportDiagnostic(Diagnostic.Create(MissingHint, tool.Method.Locations.FirstOrDefault(), tool.Method.Name, hint));
                    }
                }
            }

            source.AppendLine("    };\n}");
            output.AddSource("McpToolInventory.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        });
    }

    private sealed class Tool(IMethodSymbol method, AttributeData attribute)
    {
        public IMethodSymbol Method { get; } = method;
        public AttributeData Attribute { get; } = attribute;
        public string? Name { get; } = attribute.NamedArguments.FirstOrDefault(static argument => argument.Key == "Name").Value.Value as string;
    }
}